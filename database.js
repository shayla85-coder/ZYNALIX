async function initializeDatabase(pool) {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS services (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(120) NOT NULL UNIQUE,
      category VARCHAR(60) NOT NULL,
      price VARCHAR(80) NOT NULL,
      description VARCHAR(500) NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE TABLE IF NOT EXISTS contact_messages (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(120) NOT NULL,
      email VARCHAR(254) NOT NULL,
      service VARCHAR(120) NOT NULL,
      message VARCHAR(2000) NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE TABLE IF NOT EXISTS quotes (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(120) NOT NULL,
      email VARCHAR(254) NOT NULL,
      modality VARCHAR(20) NOT NULL CHECK (modality IN ('remote', 'onsite')),
      priority VARCHAR(20) NOT NULL CHECK (priority IN ('normal', 'urgent')),
      estimated_total NUMERIC(14, 2) NOT NULL CHECK (estimated_total >= 0),
      pending_items INTEGER NOT NULL DEFAULT 0 CHECK (pending_items >= 0),
      items JSONB NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  for (const service of DEFAULT_SERVICES) {
    await pool.query(
      `INSERT INTO services (name, category, price, description)
       VALUES ($1, $2, $3, $4) ON CONFLICT (name) DO NOTHING`,
      service
    );
  }
}

